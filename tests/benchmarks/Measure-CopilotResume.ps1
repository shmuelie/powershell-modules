<#
.SYNOPSIS
    Measures automatic resume discovery against bounded fictional inventories.
.DESCRIPTION
    Never launches Copilot or accesses the user's session home. Creates an isolated
    temporary home, starts a profile-free PowerShell process per case, and measures
    the first discovery and repeated discoveries separately (not cold disk cache).
    Reports JSON on stdout. Profiling is a separate, instrumented invocation, so
    its wrapper overhead is excluded from latency. JournalBytes is logical input
    scanned; the identity reader currently reads that input twice.

    Complete cases have 1% or 80% matches. Incomplete cases have 1% or 80%
    recoverable identities and known branch conflicts otherwise. Legacy cases
    recover ADO identity from lifecycle context. All journals contain fictional
    conversation padding; one shared hard-linked template bounds physical storage.
    Recovery remains real; Git is fail-closed except for the optional RecordedGit
    case, which only reads a newly created fictional local repository's origin.
    Native CLI conversation loading is deliberately not measured.
.PARAMETER ModulePath
    Source manifest to measure. Can point to an isolated baseline module copy.
.PARAMETER Count
    Inventory sizes, bounded to 10,000 sessions per case.
.PARAMETER BaselineModulePath
    Optional isolated baseline manifest. Measures it before ModulePath on the
    same inventory, each in a separate fresh process.
.PARAMETER Scenario
    Matrix cases to measure.
.PARAMETER JournalKiB
    Approximate journal size for incomplete/legacy cases (default 1024 KiB).
.EXAMPLE
    ./tests/benchmarks/Measure-CopilotResume.ps1 -Count 100,1000,10000
#>
[CmdletBinding()]
param(
    [string]$ModulePath = (Join-Path $PSScriptRoot '..' '..' 'modules' 'Shmuelie.Copilot' 'Shmuelie.Copilot.psd1'),
    [string]$BaselineModulePath,
    [ValidateRange(1, 10000)][int[]]$Count = @(100, 1000, 10000),
    [ValidateSet('CompleteUnrelated', 'CompleteMatching', 'IncompleteUnrelated', 'IncompleteMatching', 'LegacyMatching', 'RecordedGit')]
    [string[]]$Scenario = @('CompleteUnrelated', 'CompleteMatching', 'IncompleteUnrelated', 'IncompleteMatching', 'LegacyMatching'),
    [ValidateRange(1, 4096)][int]$JournalKiB = 1024,
    [ValidateRange(1, 10)][int]$Repeat = 3,
    [switch]$Worker,
    [string]$InventoryPath,
    [ValidateSet('Baseline', 'Current')][string]$Variant = 'Current'
)

$ErrorActionPreference = 'Stop'
$ModulePath = (Resolve-Path -LiteralPath $ModulePath).Path
if ($BaselineModulePath) { $BaselineModulePath = (Resolve-Path -LiteralPath $BaselineModulePath).Path }
if ($Worker) {
    # Only accept a fixture generated by this script, never a session-state path.
    if (-not $InventoryPath -or
        -not (Test-Path -LiteralPath (Join-Path $InventoryPath 'fictional-resume-benchmark.json'))) {
        throw 'Worker requires a marked fictional inventory.'
    }
    $fixture = Get-Content -LiteralPath (Join-Path $InventoryPath 'fictional-resume-benchmark.json') -Raw | ConvertFrom-Json
    if ($fixture.RecordedPath) {
        if ($fixture.RecordedPath -cne (Join-Path $InventoryPath 'fictional-recorded-worktree')) {
            throw 'Recorded Git path must belong to the fictional inventory.'
        }
        # Worker-local environment only. Inherited Git routing/config must never
        # redirect fixture initialization or read probes to an active repository.
        foreach ($name in @('GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR', 'GIT_INDEX_FILE',
            'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_CONFIG',
            'GIT_CONFIG_COUNT', 'GIT_CONFIG_PARAMETERS', 'GIT_TEMPLATE_DIR')) {
            # PowerShell can bind $null to an empty .NET string; Git treats a
            # present-but-empty routing/template variable differently from absent.
            Remove-Item -LiteralPath "Env:$name" -ErrorAction Ignore
        }
        $env:GIT_CONFIG_NOSYSTEM = '1'
        $env:GIT_CONFIG_GLOBAL = Join-Path $InventoryPath 'fictional-empty-gitconfig'
        [IO.File]::WriteAllText($env:GIT_CONFIG_GLOBAL, '')
        $git = (Get-Command git -CommandType Application -ErrorAction Stop).Source
        # A paired run reuses the same owned fixture, including its repository.
        if (-not (Test-Path -LiteralPath (Join-Path $fixture.RecordedPath '.git'))) {
            & $git init -q -b feature/topic $fixture.RecordedPath
            if ($LASTEXITCODE -ne 0) { throw 'Cannot initialize fictional recorded Git path.' }
            & $git -C $fixture.RecordedPath remote add origin 'https://dev.azure.com/acme/Project/_git/widget'
            if ($LASTEXITCODE -ne 0) { throw 'Cannot configure fictional local origin metadata.' }
        }
    }
    Import-Module $ModulePath -Force
    $module = Get-Module Shmuelie.Copilot
    & $module {
        param($HomePath, $RecordedPath)
        $script:BenchmarkHome = $HomePath
        $script:BenchmarkRecordedPath = $RecordedPath
        $script:BenchmarkGitExecutable = if ($RecordedPath) {
            (Get-Command git -CommandType Application -ErrorAction Stop).Source
        }
        $script:BenchmarkGitCalls = 0
        function script:Get-CopilotHome { $script:BenchmarkHome }
        function script:Get-CopilotSessionScope {
            [pscustomobject]@{ Cwd = 'fictional-current'; Repository = 'acme/Project/widget'; Branch = 'feature/topic' }
        }
        function script:git {
            if ($script:BenchmarkRecordedPath -and $args[0] -ceq '-C' -and
                $args[1] -ceq $script:BenchmarkRecordedPath -and
                (($args.Count -eq 4 -and $args[2] -ceq 'rev-parse' -and $args[3] -ceq '--is-inside-work-tree') -or
                 ($args.Count -eq 5 -and $args[2] -ceq 'config' -and $args[3] -ceq '--get-all' -and $args[4] -ceq 'remote.origin.url'))) {
                $script:BenchmarkGitCalls++
                & $script:BenchmarkGitExecutable @args
            } else { throw 'Benchmark must not invoke unallowlisted Git operations.' }
        }
    } $InventoryPath $fixture.RecordedPath

    $samples = @(
        for ($i = 0; $i -le $Repeat; $i++) {
            $watch = [Diagnostics.Stopwatch]::StartNew()
            $sessions = @(& $module { Get-CopilotResumeCandidate })
            $watch.Stop()
            [math]::Round($watch.Elapsed.TotalMilliseconds, 2)
        }
    )
    if ($sessions.Count -ne $fixture.ExpectedMatches) { throw 'Unexpected benchmark selection count.' }
    $sortWatch = [Diagnostics.Stopwatch]::StartNew()
    $sessions | Sort-Object UpdatedAt -Descending | Out-Null
    $sortWatch.Stop()
    $enumerateWatch = [Diagnostics.Stopwatch]::StartNew()
    Get-ChildItem -LiteralPath (Join-Path $InventoryPath '.copilot' 'session-state') -Directory | Out-Null
    $enumerateWatch.Stop()

    $profile = & $module {
        $script:BenchmarkGitCalls = 0
        $script:BenchmarkProfile = [ordered]@{}
        foreach ($name in @('Resolve-CopilotSessionPath', 'Get-CopilotWorkspaceField', 'Get-CopilotWorkspaceFields',
            'Split-CopilotWorkspaceLines', 'Resolve-CopilotSessionIdentity',
            'Get-CopilotLifecycleContext', 'Get-CopilotRecordedOriginIdentity', 'Get-Content')) {
            $command = Get-Command $name -ErrorAction Ignore
            if (-not $command) { continue } # Baselines predate the private bulk reader.
            $script:BenchmarkProfile[$name] = @{
                Calls = 0; Milliseconds = 0.0; Bytes = [long]0
                Original = if ($command.ScriptBlock) { $command.ScriptBlock } else { $command }
            }
        }
        # Generate parameter-compatible wrappers for the bounded discovery trace.
        $parameters = @{
            'Resolve-CopilotSessionPath' = '[string]$Id'
            'Get-CopilotWorkspaceField' = '[string]$Field, [AllowEmptyString()][string]$Content, [string]$Path'
            'Get-CopilotWorkspaceFields' = '[AllowEmptyString()][string]$Content, [string[]]$Fields'
            'Split-CopilotWorkspaceLines' = '[AllowEmptyString()][string]$Content'
            'Resolve-CopilotSessionIdentity' = '[string]$SessionPath, [string]$Cwd, [string]$Repository, [string]$Branch, $Scope'
            'Get-CopilotLifecycleContext' = '[string]$SessionPath'
            'Get-CopilotRecordedOriginIdentity' = '[string]$Path'
            'Get-Content' = '[string]$Path, [string]$LiteralPath, [switch]$Raw'
        }
        foreach ($name in $parameters.Keys) {
            if (-not $script:BenchmarkProfile.Contains($name)) { continue }
            $body = @'
[CmdletBinding()]
param(PARAMETERS)
$entry = $script:BenchmarkProfile['FUNCTION']
$entry.Calls++
if ('FUNCTION' -eq 'Get-CopilotLifecycleContext') {
    $journal = Join-Path $SessionPath 'events.jsonl'
    if (Test-Path -LiteralPath $journal) { $entry.Bytes += (Get-Item -LiteralPath $journal).Length }
}
$watch = [Diagnostics.Stopwatch]::StartNew()
try { & $entry.Original @PSBoundParameters }
finally { $entry.Milliseconds += $watch.Elapsed.TotalMilliseconds }
'@
            Set-Item -LiteralPath "Function:script:$name" -Value ([scriptblock]::Create(
                $body.Replace('PARAMETERS', $parameters[$name]).Replace('FUNCTION', $name)))
        }
        Get-CopilotResumeCandidate | Out-Null
        foreach ($name in $script:BenchmarkProfile.Keys) {
            $entry = $script:BenchmarkProfile[$name]
            [pscustomobject]@{
                Function = $name; Calls = $entry.Calls
                Milliseconds = [math]::Round($entry.Milliseconds, 2); Bytes = $entry.Bytes
            }
        }
    }
    [pscustomobject]@{
        Variant = $Variant; Scenario = $fixture.Scenario; Count = $fixture.Count; Matches = $sessions.Count
        ColdMs = $samples[0]; WarmMs = @($samples[1..$Repeat])
        WorkspaceReads = ($profile | Where-Object Function -eq 'Get-Content').Calls
        MetadataPasses = ($profile | Where-Object Function -eq 'Split-CopilotWorkspaceLines').Calls
        JournalBytes = ($profile | Where-Object Function -eq 'Get-CopilotLifecycleContext').Bytes
        GitInvocations = & $module { $script:BenchmarkGitCalls }
        EnumerationMs = [math]::Round($enumerateWatch.Elapsed.TotalMilliseconds, 2)
        SortMs = [math]::Round($sortWatch.Elapsed.TotalMilliseconds, 2)
        Profile = @($profile)
        PowerShell = $PSVersionTable.PSVersion.ToString()
    } | ConvertTo-Json -Depth 6 -Compress
    return
}

$results = @(
    foreach ($size in $Count) {
        foreach ($case in $Scenario) {
            $root = Join-Path ([IO.Path]::GetTempPath()) "copilot-resume-benchmark-$([guid]::NewGuid())"
            $state = Join-Path $root '.copilot' 'session-state'
            [void][IO.Directory]::CreateDirectory($state)
            try {
                $complete = $case.StartsWith('Complete')
                $matching = $case.EndsWith('Matching') -or $case -eq 'RecordedGit'
                $matches = [math]::Max(1, [int][math]::Floor($size * $(if ($matching) { 0.8 } else { 0.01 })))
                $fixture = @{ Scenario = $case; Count = $size; ExpectedMatches = $matches }
                $recordedPath = $null
                if ($case -eq 'RecordedGit') {
                    $recordedPath = Join-Path $root 'fictional-recorded-worktree'
                    $fixture.RecordedPath = $recordedPath
                }
                [IO.File]::WriteAllText((Join-Path $root 'fictional-resume-benchmark.json'), ($fixture | ConvertTo-Json -Compress))
                $template = Join-Path $root 'fictional-events.jsonl'
                if (-not $complete) {
                    $context = if ($case -eq 'LegacyMatching') {
                        @{ repository = 'Project/widget'; branch = 'feature/topic'; cwd = 'fictional-old'; repositoryHost = 'acme.visualstudio.com'; hostType = 'ado' }
                    } elseif ($case -eq 'RecordedGit') {
                        @{ branch = 'feature/topic'; cwd = $recordedPath }
                    } else {
                        @{ repository = 'acme/Project/widget'; branch = 'feature/topic'; cwd = 'fictional-old' }
                    }
                    $lifecycle = @{ type = 'session.start'; data = @{ context = $context } } | ConvertTo-Json -Depth 5 -Compress
                    $padding = '{"type":"assistant.message","data":{"content":"' + ('x' * 4000) + '"}}'
                    $journal = $lifecycle + "`n" + (($padding + "`n") * [math]::Ceiling($JournalKiB * 1024 / ($padding.Length + 1)))
                    [IO.File]::WriteAllText($template, $journal)
                }
                for ($i = 0; $i -lt $size; $i++) {
                    # NTFS limits hard links per file; bound each template to 500.
                    if (-not $complete -and $i % 500 -eq 0) {
                        $template = Join-Path $root "fictional-events-$i.jsonl"
                        [IO.File]::WriteAllText($template, $journal)
                    }
                    $path = Join-Path $state ('fictional-{0:d5}' -f $i)
                    [void][IO.Directory]::CreateDirectory($path)
                    $branch = if ($i -lt $matches) { 'feature/topic' } else { 'feature/unrelated' }
                    $repository = if ($complete) { 'acme/Project/widget' } elseif ($case -eq 'LegacyMatching') { 'Project/widget' } else { '' }
                    $metadata = @(
                        "cwd: $(if ($recordedPath) { $recordedPath } else { 'fictional-old' })"
                        "updated_at: $([DateTimeOffset]::Parse('2026-01-01T00:00:00Z').AddSeconds($i).ToString('o'))"
                        "summary: Fictional conversation $i"
                        "branch: $branch"
                        "repository: $repository"
                        "name: Fictional session $i"
                    ) -join "`n"
                    [IO.File]::WriteAllText((Join-Path $path 'workspace.yaml'), $metadata)
                    if (-not $complete) {
                        New-Item -ItemType HardLink -Path (Join-Path $path 'events.jsonl') -Target $template | Out-Null
                    }
                }
                $pwsh = (Get-Process -Id $PID).Path
                $variants = @(
                    if ($BaselineModulePath) { @{ Name = 'Baseline'; Path = $BaselineModulePath } }
                    @{ Name = 'Current'; Path = $ModulePath }
                )
                foreach ($version in $variants) {
                    $output = & $pwsh -NoLogo -NoProfile -NonInteractive -File $PSCommandPath -Worker -ModulePath $version.Path -InventoryPath $root -Repeat $Repeat -Variant $version.Name
                    if ($LASTEXITCODE -ne 0) { throw "Benchmark worker failed with exit code $LASTEXITCODE." }
                    $measurement = $output | ConvertFrom-Json
                    Write-Information "$case / $size / $($version.Name): cold $($measurement.ColdMs) ms; warm $($measurement.WarmMs -join ', ') ms" -InformationAction Continue
                    $measurement
                }
            } finally {
                # Only the newly generated temporary fixture is removed.
                Remove-Item -LiteralPath $root -Recurse -Force
            }
        }
    }
)
$results | ConvertTo-Json -Depth 8
